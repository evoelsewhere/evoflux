//! Port of app/cli/seed.py::write_env_credentials and app/api/routes/mcp.py::_save_env_values.

use crate::{
    parser::{universal_newlines, whitespace},
    DotenvError,
};
use indexmap::IndexMap;
use std::{collections::HashSet, ffi::OsString, io::Write, path::Path};

#[derive(Clone, Copy)]
pub enum Quote {
    None,
    Double,
}

/// `None` uses credential-line matching (including bare keys); `Double` uses
/// MCP matching (only non-comment assignments) and skips empty update sets.
/// Comments are trusted annotations supplied by the caller, not credential data.
pub struct WriteOpts<'a> {
    pub quote: Quote,
    pub empty_removes: bool,
    pub header_on_create: bool,
    pub comments: &'a [(&'a str, &'a str)],
}

impl<'a> WriteOpts<'a> {
    pub fn credentials(comments: &'a [(&'a str, &'a str)]) -> Self {
        Self {
            quote: Quote::None,
            empty_removes: true,
            header_on_create: true,
            comments,
        }
    }

    pub fn mcp() -> Self {
        Self {
            quote: Quote::Double,
            empty_removes: false,
            header_on_create: false,
            comments: &[],
        }
    }
}

fn validate(updates: &[(&str, &str)]) -> Result<(), DotenvError> {
    for (key, value) in updates {
        let mut chars = key.chars();
        if !chars
            .next()
            .is_some_and(|c| c.is_ascii_alphabetic() || c == '_')
            || !chars.all(|c| c.is_ascii_alphanumeric() || c == '_')
        {
            return Err(DotenvError::InvalidName);
        }
        if value.contains(['\r', '\n', '\0']) {
            return Err(DotenvError::InvalidValue {
                key: (*key).to_owned(),
            });
        }
    }
    Ok(())
}

fn assignment(key: &str, value: &str, quote: Quote) -> String {
    match quote {
        Quote::None => format!("{key}={value}"),
        Quote::Double => format!(
            "{key}=\"{}\"",
            value.replace('\\', "\\\\").replace('"', "\\\"")
        ),
    }
}

fn splitlines(text: &str) -> Vec<&str> {
    if text.is_empty() {
        return Vec::new();
    }
    let mut lines: Vec<_> = text
        .split([
            '\n', '\u{b}', '\u{c}', '\u{1c}', '\u{1d}', '\u{1e}', '\u{85}', '\u{2028}', '\u{2029}',
        ])
        .collect();
    if lines.last() == Some(&"") {
        lines.pop();
    }
    lines
}

fn merge(existing: Option<&str>, updates: &IndexMap<&str, &str>, opts: &WriteOpts<'_>) -> String {
    let mut lines = Vec::new();
    let mut handled = HashSet::new();
    if existing.is_none() && opts.header_on_create {
        lines.extend(
            [
                "# Generated by EvoFlux",
                "# Edit as needed. See .env.example for the full reference.",
                "",
                "APP_ENV=production",
                "",
            ]
            .map(str::to_owned),
        );
    }
    let normalized = universal_newlines(existing.unwrap_or_default());
    for line in splitlines(&normalized) {
        let key = if matches!(opts.quote, Quote::None)
            || (line.contains('=') && !line.trim_start_matches(whitespace).starts_with('#'))
        {
            line.split_once('=')
                .map_or(line, |(key, _)| key)
                .trim_matches(whitespace)
        } else {
            ""
        };
        if let Some(value) = updates.get(key) {
            handled.insert(key);
            if !opts.empty_removes || !value.is_empty() {
                lines.push(assignment(key, value, opts.quote));
            }
        } else {
            lines.push(line.to_owned());
        }
    }
    for (key, value) in updates {
        if handled.contains(key) || (opts.empty_removes && value.is_empty()) {
            continue;
        }
        lines.push(assignment(key, value, opts.quote));
        if let Some((_, comment)) = opts.comments.iter().rev().find(|(name, _)| name == key) {
            lines.push((*comment).to_owned());
        }
    }
    let content = lines.join("\n") + "\n";
    if cfg!(windows) {
        content.replace('\n', "\r\n")
    } else {
        content
    }
}

fn parent(path: &Path) -> &Path {
    path.parent()
        .filter(|parent| !parent.as_os_str().is_empty())
        .unwrap_or_else(|| Path::new("."))
}

pub(crate) async fn atomic_write(path: &Path, content: String) -> Result<(), DotenvError> {
    let path = path.to_owned();
    tokio::task::spawn_blocking(move || -> Result<(), std::io::Error> {
        let name = path.file_name().ok_or_else(|| {
            std::io::Error::new(
                std::io::ErrorKind::InvalidInput,
                "dotenv target needs a file name",
            )
        })?;
        let mut prefix = OsString::from(".");
        prefix.push(name);
        prefix.push(".");
        let mut builder = tempfile::Builder::new();
        builder.prefix(&prefix).suffix(".tmp");
        #[cfg(unix)]
        {
            use std::os::unix::fs::PermissionsExt;
            builder.permissions(std::fs::Permissions::from_mode(0o600));
        }
        let mut temporary = builder.tempfile_in(parent(&path))?;
        temporary.write_all(content.as_bytes())?;
        temporary.as_file().sync_all()?;
        // Persist replaces atomically (MoveFileExW on Windows, rename on Unix).
        // PersistError owns the temporary; dropping it removes it on failure.
        temporary.persist(&path).map_err(|error| error.error)?;
        Ok(())
    })
    .await??;
    Ok(())
}

/// Validate the entire batch before touching the filesystem, then atomically
/// replace the UTF-8 file. Returns true only when a file was created.
/// Callers serialize concurrent merges and own process-environment updates.
pub async fn merge_write(
    path: &Path,
    updates: &[(&str, &str)],
    opts: &WriteOpts<'_>,
) -> Result<bool, DotenvError> {
    validate(updates)?;
    if updates.is_empty() && matches!(opts.quote, Quote::Double) {
        return Ok(false);
    }
    tokio::fs::create_dir_all(parent(path)).await?;
    let existing = match tokio::fs::read_to_string(path).await {
        Ok(text) => Some(text),
        Err(error) if error.kind() == std::io::ErrorKind::NotFound => None,
        Err(error) => return Err(error.into()),
    };
    let updates = updates.iter().copied().collect();
    let content = merge(existing.as_deref(), &updates, opts);
    atomic_write(path, content).await?;
    Ok(existing.is_none())
}

#[cfg(test)]
mod tests {
    use super::parent;
    use std::path::Path;

    #[test]
    fn temporary_files_use_target_directory_including_bare_relative_names() {
        assert_eq!(
            parent(Path::new("credentials/.env")),
            Path::new("credentials")
        );
        assert_eq!(parent(Path::new(".env")), Path::new("."));
        assert_eq!(parent(Path::new("./.env")), Path::new("."));
    }
}
