    folder.mkdir(parents=True)
    (folder / "openai.svg").write_bytes(LOGO)
    plain = client.get("/api/settings/providers/openai/logo")
    assert plain.status_code == 200
    assert plain.content == LOGO
    assert plain.headers["content-type"] == "image/svg+xml"
    assert plain.headers["cache-control"] == "public, max-age=604800"
    assert plain.headers["content-security-policy"] == "default-src 'none'; style-src 'unsafe-inline'"
    assert plain.headers["x-content-type-options"] == "nosniff"
    tinted = client.get("/api/settings/providers/openai/logo", params={"color": "#112233"})
    assert tinted.content == LOGO.replace(b"currentColor", b"#112233").replace(
        b'fill="black"', b'fill="#112233"'
    )
    # The cache keeps the original bytes; only the response is tinted.
    assert (folder / "openai.svg").read_bytes() == LOGO


