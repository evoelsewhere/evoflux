def test_manual_provider_stays_disconnected_until_its_models_are_listed(
    client, mock_provider
) -> None:
    # Ollama is never contacted by a listing; listing its models needs the
    # native /api/tags the mock provider does not serve, so only the disconnected
    # state is covered here (NOTES, test map).
    base = f"{mock_provider.base_url}/v1"
    client.put("/api/settings/providers/ollama", json={"extra": {"OLLAMA_BASE_URL": base}})
    item = providers(client)["ollama"]
    assert item["is_saved"] is False
    assert item["is_configured"] is False
    assert item["is_reachable"] is None
    assert item["saved_credentials"] == {"OLLAMA_BASE_URL": base}
    assert mock_provider.side_requests == [] and mock_provider.requests == []
    # DELETE on a local provider is a no-op: the saved base URL stays.
    client.delete("/api/settings/providers/ollama")
    assert providers(client)["ollama"]["saved_credentials"] == {"OLLAMA_BASE_URL": base}


