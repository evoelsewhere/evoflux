# ── concurrent writers ─────────────────────────────────────────────────────

API_KEY_PROVIDERS = ("anthropic", "openai", "router9", "cliproxy", "xai", "deepseek", "mistral", "cohere")


def test_concurrent_saves_of_different_providers_all_persist(client, config_dir, secrets) -> None:
    keys = {pid: secrets.new(pid) for pid in API_KEY_PROVIDERS}

    def save(pid: str) -> int:
        return client.put(f"/api/settings/providers/{pid}", json={"api_key": keys[pid]}).status_code

    with ThreadPoolExecutor(max_workers=8) as pool:
        statuses = list(pool.map(save, API_KEY_PROVIDERS))
    assert statuses == [200] * len(API_KEY_PROVIDERS)
    values = env_values(config_dir)
    for pid in API_KEY_PROVIDERS:
        name = next(
            c["name"] for c in providers(client)[pid]["credentials"] if c["secret"]
        )
        assert values[name] == keys[pid], pid
    lines = [line for line in env_lines(config_dir) if line]
    assert len(lines) == len(set(lines))


def test_concurrent_visible_models_and_saves_do_not_lose_updates(client, config_dir, secrets) -> None:
    def work(index: int) -> int:
        pid = API_KEY_PROVIDERS[index % len(API_KEY_PROVIDERS)]
        if index % 2:
            return client.put(
                f"/api/settings/providers/{pid}/visible-models", json={"models": [f"m{index}"]}
            ).status_code
        return client.put(f"/api/settings/providers/{pid}", json={"api_key": secrets.new(f"k{index}")}).status_code

    with ThreadPoolExecutor(max_workers=8) as pool:
        statuses = list(pool.map(work, range(16)))
    assert statuses == [200] * 16
    saved = yaml.safe_load((config_dir / "settings.yaml").read_text(encoding="utf-8"))
    assert set(saved["providers"]) == {API_KEY_PROVIDERS[i % 8] for i in range(1, 16, 2)}
