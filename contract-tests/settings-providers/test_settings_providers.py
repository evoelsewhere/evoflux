def test_seed_installs_agents_with_the_chosen_model(client, config_dir, snapshot) -> None:
    response = client.post("/api/settings/seed", json={"provider_model": "anthropic:mock-model"})
    assert response.status_code == 200
    body = response.json()
    assert set(body) == {"agents_written", "skills_written", "configs_written", "agents_removed", "source"}
    assert body["source"] == "local"
    assert body["agents_removed"] == []
    assert sorted(body["agents_written"]) == sorted(
        str(p.relative_to(config_dir / "agents")) for p in (config_dir / "agents").rglob("*.md")
    )
    snapshot.check(
        "seed_install.json",
        {**body, "agents_written": sorted(name.replace("\\", "/") for name in body["agents_written"])},
    )
    texts = [p.read_text(encoding="utf-8") for p in (config_dir / "agents").rglob("*.md")]
    assert any("anthropic:mock-model" in text for text in texts)
    assert not any("__PROVIDER_MODEL__" in text for text in texts)


