def providers(client) -> dict[str, dict]:
    body = client.get("/api/settings/providers").json()
    return {item["id"]: item for item in body["providers"]}


# ── GET /providers ─────────────────────────────────────────────────────────


def test_list_shape_and_catalog(client, snapshot) -> None:
    response = client.get("/api/settings/providers")
    assert response.status_code == 200
    body = response.json()
    assert set(body) == {"providers", "has_any_configured"}
    assert body["has_any_configured"] is False
    items = body["providers"]
    assert len(items) > 100
    ids = [item["id"] for item in items]
    assert len(set(ids)) == len(ids)
    for item in items:
        assert set(item) == PROVIDER_KEYS, item["id"]
        assert item["kind"] in {"api_key", "oauth", "local", "cloud_creds"}
        assert item["is_saved"] is False
        assert item["is_configured"] is False
        assert item["saved_credentials"] == {}
        assert item["is_reachable"] is None
        assert item["visible_models"] == []
        assert isinstance(item["model_count"], int)
        assert isinstance(item["rank"], int)
    by_id = {item["id"]: item for item in items}
    snapshot.check("providers_catalog_ids.json", ids)
    snapshot.check(
        "providers_static_fields.json",
        {pid: {key: by_id[pid][key] for key in STATIC_KEYS} for pid in SNAPSHOT_IDS},
    )


