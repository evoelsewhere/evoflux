def test_concurrent_provider_tests_do_not_leak_keys_between_requests(
    client, mock_provider, secrets
) -> None:
    def run(index: int) -> dict:
        response = client.post(
            "/api/settings/providers/anthropic/test",
            json={
                "api_key": secrets.new(f"candidate-{index}"),
                "model": "mock-model",
                "extra": {"ANTHROPIC_BASE_URL": mock_provider.base_url},
            },
        )
        secrets.assert_response_clean("POST /test", response)
        return response.json()

    with ThreadPoolExecutor(max_workers=6) as pool:
        results = list(pool.map(run, range(6)))
    assert [r["ok"] for r in results] == [True] * 6
    assert providers(client)["anthropic"]["is_saved"] is False


